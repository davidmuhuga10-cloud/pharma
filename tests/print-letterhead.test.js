// The printed-report LETTERHEAD (Nov 2026): pharmacy name and contacts left, report title and period right,
// KRA PIN and "printed by" shown, a footer on every page, and a total line that can never be left alone on a page.
// Runs the real js/export.js in a small sandbox, without a browser.
// Run from the project folder:   node tests/print-letterhead.test.js
//
// The page-layout side of this (no blank pages, nothing cut off, page numbers, the total staying with its rows)
// was measured on real PDFs: 113 row counts x A4/A5/Letter/landscape, 0 blank pages, 0 clipped, 0 stranded totals.
// That harness needs a browser, so it is not part of npm test; this file guards the markup and CSS it depends on.
const fs = require('fs'), path = require('path'), vm = require('vm');
const ROOT = path.join(__dirname, '..');
const read = f => fs.readFileSync(path.join(ROOT, f), 'utf8');
let failed = 0;
const check = (ok, msg) => { if (!ok) { failed++; console.error('FAIL ' + msg); } };

function makeCtx(pharmacy, profile, withDocument) {
  const area = { className: '', innerHTML: '' };
  const styleEl = { id: '', textContent: '' };
  const ctx = {
    console, $: sel => sel === '#printArea' ? area : null, setTimeout: () => {}, window: { print() {} },
    STATE: { pharmacy, profile }, icon: () => '', area, styleEl
  };
  if (withDocument) {
    ctx.document = { head: { appendChild: el => { ctx.appended = el; } }, getElementById: id => (ctx.appended && ctx.appended.id === id ? ctx.appended : null), createElement: () => styleEl };
  }
  vm.createContext(ctx);
  vm.runInContext(['esc', 'fmt', 'fmtDate', 'daysUntil'].map(n => {
    const src = read('js/core.js'), start = src.indexOf('function ' + n + '(');
    let depth = 0, i = src.indexOf('{', start);
    for (; i < src.length; i++) { if (src[i] === '{') depth++; else if (src[i] === '}' && --depth === 0) break; }
    return src.slice(start, i + 1);
  }).join('\n') + '\n' + read('js/export.js'), ctx);
  return ctx;
}
const run = (ctx, c) => vm.runInContext(c, ctx);

const FULL = { name: 'Afya Bora Chemist', address: 'Kiambu Road', town: 'Nairobi', phone: '0722 000 111', email: 'a@b.example', kra_pin: 'P051234567X' };

// ---- the head ----
{
  const c = makeCtx(FULL, { full_name: 'Grace Kamau' });
  const h = run(c, "letterheadHtml('Sales Report', '1 Nov – 10 Nov 2026', false)");
  check(/class="plh-left"[\s\S]*Afya Bora Chemist[\s\S]*class="print-titlebar"/.test(h), 'name and contacts come first (left), the title block after (right)');
  check(/class="print-ribbon">Sales Report</.test(h) && /class="print-period">1 Nov – 10 Nov 2026</.test(h), 'the title and its period are separate lines in the right-hand block');
  check(/KRA PIN: P051234567X/.test(h), 'the KRA PIN is printed on a report when the owner has entered one');
  check(/Kiambu Road/.test(h) && /Nairobi · 0722 000 111/.test(h) && /a@b\.example/.test(h), 'address, town, phone and email each get their own line');
  check(/class="plh-line"/.test(h), 'a double rule closes the head');
  const r = run(c, "letterheadHtml('Receipt', '', true)");
  check(!/KRA PIN|plh-/.test(r) && /print-title/.test(r), 'the till receipt is untouched: no KRA PIN line, no letterhead layout');
}
{
  // a pharmacy that filled in only its name: no empty lines, no stray separators, no empty period line
  const c = makeCtx({ name: 'Medicare Pharmacy' }, null);
  const h = run(c, "letterheadHtml('Low Stock Report', '', false)");
  check(!/pmeta/.test(h) && !/KRA/.test(h) && !/print-period/.test(h) && !/undefined|null/.test(h), 'a name-only pharmacy prints a tidy head: no empty contact lines, no KRA line, no empty period, no "undefined"');
  // markup in a name or subtitle is escaped
  const c2 = makeCtx({ name: '<b>X</b> & Sons', kra_pin: '<i>' }, null);
  const h2 = run(c2, "letterheadHtml('T<', 'S\"<script>', false)");
  check(!/<b>X|<i>|<script>/.test(h2) && /&lt;b&gt;X/.test(h2), 'names, PINs and subtitles are escaped');
}

// ---- printHtml: who printed it, and no in-flow footer ----
{
  const c = makeCtx(FULL, { full_name: 'Grace Kamau' }, true);
  run(c, "printHtml('Sales Report', 'Today', '<p>x</p>', '6 transactions')");
  check(/Printed [^<]* · by Grace Kamau/.test(c.area.innerHTML), 'the "Printed ... by <person>" line names who printed it');
  check(/6 transactions/.test(c.area.innerHTML) && !/print-bandfoot/.test(c.area.innerHTML), 'the summary stays in the report; the footer is not part of the report flow');
  check(/@page \{ @bottom-left \{ content: "Afya Bora Chemist · Generated by Pharma"/.test(c.styleEl.textContent), 'the page footer is set as a page-margin box with the pharmacy name');
  run(c, "printHtml('Receipt', '', '<p>y</p>', null, { receipt: true })");
  check(c.styleEl.textContent === '', 'printing a receipt clears the footer, so the next receipt never carries a report footer');
}
{
  // a pharmacy name with a quote or a backslash must not be able to break out of the CSS string
  const c = makeCtx({ name: 'Bob"s } body { display:none } \\ Chemist\nLtd' }, null, true);
  run(c, "printHtml('R', '', '<p>x</p>')");
  const css = c.styleEl.textContent;
  check(/^@page \{ @bottom-left \{ content: "[^"\\]*(?:\\.[^"\\]*)*"; font: 9px Arial, sans-serif; color: #000; \} \}$/.test(css), 'the footer text stays inside its CSS string (quotes and backslashes are escaped), so a name cannot inject CSS');
  check(!/\n/.test(css), 'line breaks in a name are flattened');
  // a very long name is shortened in the footer only (it crowded the page number out of a small page)
  const long = 'Mama Lucy Memorial Community Chemist and General Wholesale Pharmaceutical Distributors Limited';
  const c2 = makeCtx({ name: long }, null, true);
  run(c2, "printHtml('R', '', '<p>x</p>')");
  check(/…/.test(c2.styleEl.textContent) && !/Distributors Limited/.test(c2.styleEl.textContent) && /Mama Lucy Memorial/.test(c2.area.innerHTML), 'a very long pharmacy name is shortened in the footer but shown in full in the letterhead');
  // no document at all (these tests, a worker): printing must not throw
  const c3 = makeCtx(FULL, null, false);
  let threw = false; try { run(c3, "printHtml('R', '', '<p>x</p>')"); run(c3, "printHtml('Receipt', '', '<p>y</p>', null, { receipt: true })"); } catch (e) { threw = true; }
  check(!threw, 'printing works with no document available (and a receipt does not need a pharmacy-name variable)');
}

// ---- the total line travels with the last data row ----
{
  const c = makeCtx(FULL, null, false);
  const t = run(c, "tableHtml(['Drug','Qty'], [['A','1'],['B','2'],['C','3']], 'Total: 3')");
  const tfoot = (t.match(/<tfoot>[\s\S]*<\/tfoot>/) || [''])[0];
  check(/class="lastrow"[\s\S]*<td class="no">3<\/td>[\s\S]*>C</.test(tfoot) && /Total: 3/.test(tfoot), 'with a total, the LAST data row sits in the tfoot beside it, so a page break can never leave the total alone');
  const tbody = (t.match(/<tbody>[\s\S]*<\/tbody>/) || [''])[0];
  check((tbody.match(/<tr/g) || []).length === 2 && !/>C</.test(tbody), 'the other rows stay in the tbody, numbered 1 and 2');
  check(!/class="lastrow"/.test(run(c, "tableHtml(['Drug'], [['A'],['B']], '')")), 'with no total line, every row stays in the tbody');
  check(/<tfoot><tr><td colspan="2">Total: 0<\/td><\/tr><\/tfoot>/.test(run(c, "tableHtml(['Drug'], [], 'Total: 0')")), 'an empty report with a total line still prints the total on its own');
}

// ---- the CSS this relies on ----
const css = read('style.css');
check(/\.print-table tfoot\s*\{\s*break-inside:\s*avoid/.test(css), 'the tfoot (last row + total) is kept in one piece');
check(/@page\s*\{[^}]*margin:\s*10mm 9mm 15mm/.test(css), 'every page has real margins, so the page number has room');
check(/@page receipt80\s*\{[^@]*@bottom-right\s*\{\s*content:\s*none;\s*\}\s*@bottom-left\s*\{\s*content:\s*none/.test(css), 'the receipt page has neither the page number nor the report footer');
check(/\.print-letterhead\s*\{[^}]*display:\s*flex[^}]*justify-content:\s*space-between/.test(css.replace(/\s+/g, ' ')), 'the letterhead lays the name block and the title block out side by side');

if (failed) { console.error(failed + ' check(s) failed'); process.exit(1); }
console.log('print letterhead: ok');
